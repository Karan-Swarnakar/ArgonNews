// Note: Oracle, SoftBank, CoreWeave, ZT Systems, Scale AI, Silo AI, MosaicML,
// Console, TSMC, and Venture/Investor syndicates have no verified vector mark
// available in the sourced icon libraries -- they intentionally fall back to
// the monogram badge below rather than risk an inaccurate or invented logo.

export function resolveLogoKey(companyName: string): string | null {
  const clean = companyName.trim().toLowerCase();
  return NAME_TO_KEY[clean] || null;
}

const SHORT_LABEL_OVERRIDE: Record<string, string> = {
  'google / alphabet': 'Google',
  'amazon / aws': 'Amazon',
};

/** Compact, breathing-room-friendly label for canvas name tags below a bubble. */
export function getShortLabel(companyName: string): string {
  const override = SHORT_LABEL_OVERRIDE[companyName.trim().toLowerCase()];
  if (override) return override;
  // Strip any parenthetical syndicate/investor detail for a clean single-line tag.
  return companyName.replace(/\s*\([^)]*\)/g, '').trim();
}

export function getCompanyLogo(companyName: string): LogoDef | null {
  const key = resolveLogoKey(companyName);
  return key ? LOGO_DATA[key] || null : null;
}

// Hand-picked disambiguation for fallback monograms where the generic
// first-letters heuristic would collide (e.g. CoreWeave / Console both -> "CO").
const INITIALS_OVERRIDE: Record<string, string> = {
  oracle: 'OR',
  softbank: 'SB',
  'zt systems': 'ZT',
  coreweave: 'CW',
  mosaicml: 'MC',
  'scale ai': 'SC',
  'silo ai': 'SL',
  console: 'CN',
  railway: 'RW',
  'inflection ai': 'IF',
  investors: 'IV',
};

/** Short initials used for the elegant monogram fallback when no brand mark is available. */
export function getCompanyInitials(companyName: string): string {
  const cleaned = companyName.replace(/\s*\([^)]*\)/g, '').trim();
  const override = INITIALS_OVERRIDE[cleaned.toLowerCase()];
  if (override) return override;
  const words = cleaned.split(/[\s/]+/).filter(Boolean);
  if (words.length === 0) return '?';
  if (words.length === 1) return words[0].slice(0, 2).toUpperCase();
  return (words[0][0] + words[1][0]).toUpperCase();
}

const pathCache = new Map<string, Path2D>();
function getPath2D(d: string): Path2D {
  let p = pathCache.get(d);
  if (!p) {
    p = new Path2D(d);
    pathCache.set(d, p);
  }
  return p;
}

/**
 * Draws a company's brand mark centered at (cx, cy), scaled uniformly from its
 * native 24x24 viewBox so every logo -- regardless of native aspect -- occupies
 * the same visual footprint. `monoInk` supplies the fill for single-color marks
 * (OpenAI, Anthropic, xAI, Apple) so they can adapt to the surrounding surface.
 */
export function drawCompanyLogo(
  ctx: CanvasRenderingContext2D,
  logo: LogoDef,
  cx: number,
  cy: number,
  size: number,
  monoInk: string
): void {
  const scale = size / 24;
  ctx.save();
  ctx.translate(cx - size / 2, cy - size / 2);
  ctx.scale(scale, scale);
  for (const p of logo.paths) {
    ctx.fillStyle = p.fill === 'currentColor' ? monoInk : p.fill;
    ctx.fill(getPath2D(p.d));
  }
  ctx.restore();
}

/** Elegant neutral monogram badge for companies without a sourced brand mark. */
export function drawCompanyMonogram(
  ctx: CanvasRenderingContext2D,
  companyName: string,
  cx: number,
  cy: number,
  radius: number,
  textColor: string
): void {
  const initials = getCompanyInitials(companyName);
  ctx.save();
  ctx.font = `600 ${Math.round(radius * 0.72)}px "Plus Jakarta Sans", -apple-system, sans-serif`;
  ctx.textAlign = 'center';
  ctx.textBaseline = 'middle';
  ctx.fillStyle = textColor;
  ctx.fillText(initials, cx, cy + radius * 0.03);
  ctx.restore();
}

